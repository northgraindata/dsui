/**
 * Copies Dagster's kind icons into the adapter so the lineage graph shows
 * the same logos as Dagster's own UI, without loading anything at runtime.
 *
 * Usage, from the repository root:
 *   bun packages/adapter-dagster/scripts/sync-kind-icons.ts [commit]
 *
 * The icons and their kind mapping come from dagster-io/dagster under the
 * Apache License 2.0, the same licence as this repository (see LICENSE).
 */
import { writeFile } from "node:fs/promises";
import { join } from "node:path";

/** Pinned so a sync is reproducible; pass a newer commit to update. */
const DEFAULT_COMMIT = "05ed5f2cd6ae62c880740265978ccd23aaddb507";
/** Larger logos would bloat the browser bundle; their kinds keep a glyph. */
const MAX_ICON_BYTES = 16 * 1024;
const GRAPH_DIR = "js_modules/ui-core/src/graph";

const commit = process.argv[2] ?? DEFAULT_COMMIT;
if (!/^[0-9a-f]{40}$/.test(commit))
  throw new Error("Pass a full 40-character Dagster commit SHA");
const packageDir = join(import.meta.dir, "..");
const raw = (path: string) =>
  `https://raw.githubusercontent.com/dagster-io/dagster/${commit}/${path}`;

async function fetchText(path: string): Promise<string> {
  const response = await fetch(raw(path));
  if (!response.ok) throw new Error(`${path}: HTTP ${response.status}`);
  return response.text();
}

/** Compact data URI; smaller than base64 for SVG markup. */
function svgDataUri(svg: string): string {
  const compact = svg
    .replace(/<\?xml[^>]*>/g, "")
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/\s+/g, " ")
    .replace(/> </g, "><")
    // Icons draw on a 16–24px canvas, where 0.01 is far below a pixel.
    .replace(/(\d+\.\d{2})\d+/g, "$1")
    .trim()
    .replace(/"/g, "'");
  const encoded = encodeURIComponent(compact)
    .replace(/%20/g, " ")
    .replace(/%3D/g, "=")
    .replace(/%3A/g, ":")
    .replace(/%2F/g, "/")
    .replace(/%27/g, "'");
  return `data:image/svg+xml,${encoded}`;
}

interface KnownTag {
  label: string;
  iconName?: string;
  mono: boolean;
}

/** Reads `import name from './kindtag-images/file'` lines. */
function parseImports(source: string): Map<string, string> {
  const imports = new Map<string, string>();
  for (const match of source.matchAll(
    /^import (\w+) from '\.\/kindtag-images\/([^']+)';$/gm,
  )) {
    const [, name, file] = match;
    if (name && file) imports.set(name, file);
  }
  return imports;
}

/** Reads each `key: {icon, content, blackAndWhite}` entry of KNOWN_TAGS. */
function parseKnownTags(source: string): Map<string, KnownTag> {
  const start = source.indexOf("export const KNOWN_TAGS");
  const end = source.indexOf("\n};", start);
  if (start < 0 || end < 0) throw new Error("KNOWN_TAGS was not found");
  const tags = new Map<string, KnownTag>();
  for (const match of source
    .slice(start, end)
    .matchAll(/^ {2}(\w+): \{([\s\S]*?)\},?$/gm)) {
    const [, key, body = ""] = match;
    const label = /content: (['"])(.*?)\1/.exec(body)?.[2];
    if (!key || !label) continue;
    tags.set(key, {
      label,
      iconName: /icon: (\w+)/.exec(body)?.[1],
      mono: /blackAndWhite: true/.test(body),
    });
  }
  return tags;
}

const source = await fetchText(`${GRAPH_DIR}/OpTags.tsx`);
const imports = parseImports(source);
const tags = parseKnownTags(source);
if (tags.size < 100)
  throw new Error(
    `Only ${tags.size} kinds parsed; the format may have changed`,
  );

const icons = new Map<string, string>();
const skipped: string[] = [];
for (const name of new Set(
  [...tags.values()].flatMap((tag) => (tag.iconName ? [tag.iconName] : [])),
)) {
  const file = imports.get(name);
  if (!file?.endsWith(".svg")) {
    skipped.push(`${name} (not an SVG)`);
    continue;
  }
  const svg = await fetchText(`${GRAPH_DIR}/kindtag-images/${file}`);
  if (svg.length > MAX_ICON_BYTES) {
    skipped.push(`${name} (${Math.round(svg.length / 1024)} KB)`);
    continue;
  }
  icons.set(name, svgDataUri(svg));
}

/** Bare keys where possible, matching how the repository formats code. */
const property = (name: string) =>
  /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
const iconRef = (name: string) =>
  /^[A-Za-z_$][\w$]*$/.test(name)
    ? `icons.${name}`
    : `icons[${JSON.stringify(name)}]`;

const iconLines = [...icons]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([name, uri]) => `  ${property(name)}: ${JSON.stringify(uri)},`);
const kindLines = [...tags]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([key, tag]) => {
    const fields = [`label: ${JSON.stringify(tag.label)}`];
    if (tag.iconName && icons.has(tag.iconName))
      fields.push(`icon: ${iconRef(tag.iconName)}`);
    if (tag.mono) fields.push("mono: true");
    return `  ${property(key)}: { ${fields.join(", ")} },`;
  });

const output = `// Generated by scripts/sync-kind-icons.ts from dagster-io/dagster@${commit}.
// Do not edit by hand; run the script to update.
//
// Icon files are Copyright 2025 Dagster Labs, Inc., copied under the Apache
// License 2.0 (see LICENSE at the repository root), minified and embedded as
// data URIs. The logos they depict are trademarks of their respective owners
// and are used only to identify the technology an asset uses.
// biome-ignore-all lint/style/noExcessiveLinesPerFile: generated icon data

export interface DagsterKind {
  label: string;
  icon?: string;
  /** Single-colour logo meant to be tinted to the surrounding text colour. */
  mono?: true;
}

const icons = {
${iconLines.join("\n")}
};

/** Keyed by Dagster's normalised kind name; see \`kindKey\` in kinds.ts. */
export const DAGSTER_KINDS: Record<string, DagsterKind> = {
${kindLines.join("\n")}
};
`;

const outputPath = join(packageDir, "src/components/kind-icons.generated.ts");
await writeFile(outputPath, output);
// Leave the file exactly as the repository's formatter would write it.
const format = Bun.spawnSync([
  "bunx",
  "biome",
  "format",
  "--write",
  outputPath,
]);
if (format.exitCode !== 0)
  throw new Error(`biome format failed: ${format.stderr.toString()}`);

console.log(
  `${tags.size} kinds, ${icons.size} icons embedded (${Math.round(output.length / 1024)} KB)`,
);
if (skipped.length) console.log(`Skipped: ${skipped.join(", ")}`);
