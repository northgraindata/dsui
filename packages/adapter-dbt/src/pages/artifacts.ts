function explorerFor(
  artifactName: ArtifactName,
  source: ReturnType<typeof artifactDetail>,
) {
  if (artifactName === "manifest.json") return manifestExplorer(source);
  if (artifactName === "semantic_manifest.json")
    return semanticExplorer(source);
  if (artifactName === "catalog.json") return catalogExplorer(source);
  if (artifactName === "run_results.json") return runResultsExplorer(source);
  if (artifactName === "freshness.json" || artifactName === "sources.json")
    return Tabs({
      variant: "detail",
      items: [
        {
          label: "Freshness",
          content: Table({
            source: freshnessRows(),
            columns: [
              { id: "uniqueId", label: "Source" },
              { id: "status", label: "Status" },
              { id: "maxLoadedAt", label: "Last loaded" },
              { id: "snapshottedAt", label: "Checked" },
              { id: "error", label: "Error" },
            ],
            searchable: true,
          }),
        },
        { label: "Raw JSON", content: rawArtifact(source) },
      ],
    });
  if (artifactName === "graph_summary.json")
    return Tabs({
      variant: "detail",
      items: [
        {
          label: "Graph summary",
          content: Table({
            source: graphSummaryRows(),
            columns: [
              { id: "name", label: "Node" },
              { id: "type", label: "Type" },
              { id: "successors", label: "Downstream nodes" },
            ],
            searchable: true,
          }),
        },
        { label: "Raw JSON", content: rawArtifact(source) },
      ],
    });
  if (artifactName === "osi_document.json")
    return Tabs({
      variant: "detail",
      items: [
        {
          label: "Overview",
          content: KeyValue({
            title: "Apache Ossie document",
            source: osiOverview(),
          }),
        },
        { label: "Raw JSON", content: rawArtifact(source) },
      ],
    });
  return rawArtifact(source);
}

export const artifactsPage = definePage({
  path: "/artifacts",
  render: () => [
    PageHeader({
      title: "Artifacts",
      description: "Generated dbt artifacts in the local target directory.",
    }),
    Table({
      source: artifacts(),
      columns: [
        { id: "name", label: "Artifact" },
        { id: "present", label: "Available" },
        { id: "schemaVersion", label: "Schema version" },
        { id: "warning", label: "Warning" },
      ],
      rowLink: {
        path: "/artifacts/:artifactName",
        params: { artifactName: "name" },
      },
    }),
  ],
});

export const artifactDetailPage = definePage({
  path: "/artifacts/:artifactName",
  render: ({ params }) => {
    const artifactName = isArtifactName(params.artifactName)
      ? params.artifactName
      : artifactNames[0];
    const source = artifactDetail({ artifactName });
    return [
      PageHeader({
        title: params.artifactName,
        description: "Explore dbt metadata, results, lineage, and raw output.",
      }),
      Section({
        title: "Artifact explorer",
        content: explorerFor(artifactName, source),
      }),
    ];
  },
});
