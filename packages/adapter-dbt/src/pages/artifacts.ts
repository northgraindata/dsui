function isArtifactName(value: string): value is ArtifactName {
  return artifactNames.includes(value as ArtifactName);
}

function rawArtifact(source: ReturnType<typeof artifactDetail>) {
  return Resource({
    source,
    content: CodeBlock({
      label: "JSON",
      value: { field: "content" },
      language: "text",
    }),
  });
}

function manifestExplorer(source: ReturnType<typeof artifactDetail>) {
  return Tabs({
    variant: "detail",
    items: [
      {
        label: "Overview",
        content: Columns({
          columns: [
            {
              weight: 1,
              content: Section({
                title: "Manifest",
                description: "Project and generation metadata.",
                content: Resource({
                  source: manifestOverview(),
                  content: KeyValue({
                    title: "Details",
                    source: manifestOverview(),
                  }),
                }),
              }),
            },
            {
              weight: 2,
              content: Section({
                title: "Raw artifact",
                description: "The exact manifest generated by dbt.",
                content: rawArtifact(source),
              }),
            },
          ],
        }),
      },
      {
        label: "Models",
        content: Table({
          source: models(),
          columns: [
            { id: "name", label: "Model" },
            { id: "package", label: "Package" },
            { id: "schema", label: "Schema" },
            { id: "materialized", label: "Materialized" },
            { id: "dependsOn", label: "Upstream" },
          ],
          searchable: true,
          rowLink: {
            path: "/models/:modelId",
            params: { modelId: "uniqueId" },
          },
        }),
      },
      {
        label: "Lineage",
        content: DependencyGraph({
          source: runGraph({ runId: "local-latest" }),
          idField: "graphId",
          dependsOnField: "upstreamGraphIds",
          labelField: "name",
          detailField: "detail",
          stateField: "state",
        }),
      },
      {
        label: "Sources & tests",
        content: Columns({
          columns: [
            {
              content: Section({
                title: "Sources",
                content: Table({
                  source: sources(),
                  columns: [
                    { id: "sourceName", label: "Source" },
                    { id: "name", label: "Table" },
                    { id: "status", label: "Freshness" },
                  ],
                  searchable: true,
                }),
              }),
            },
            {
              content: Section({
                title: "Tests",
                content: Table({
                  source: tests(),
                  columns: [
                    { id: "name", label: "Test" },
                    { id: "attachedTo", label: "Attached to" },
                    { id: "status", label: "Status" },
                  ],
                  searchable: true,
                }),
              }),
            },
          ],
        }),
      },
      { label: "Raw JSON", content: rawArtifact(source) },
    ],
  });
}

